import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { ShieldCheck, ShieldAlert, Loader2, ArrowLeft, Camera } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { verifySignature, ReportPayload } from '@/lib/reportSignature';

type Status = 'loading' | 'valid' | 'invalid' | 'no-data';

const Verify = () => {
  const [status, setStatus] = useState<Status>('loading');
  const [payload, setPayload] = useState<ReportPayload | null>(null);

  useEffect(() => {
    document.title = 'Verify Report Card — EduBel';
    const hash = window.location.hash.startsWith('#') ? window.location.hash.slice(1) : '';
    const params = new URLSearchParams(hash);
    const d = params.get('d');
    const s = params.get('s');
    if (!d || !s) {
      setStatus('no-data');
      return;
    }
    verifySignature(d, s).then(({ valid, payload }) => {
      setPayload(payload);
      setStatus(valid ? 'valid' : 'invalid');
    });
  }, []);

  return (
    <div className="min-h-screen bg-background flex flex-col">
      <header className="border-b border-border/40 px-4 py-3 flex items-center justify-between">
        <Link to="/" className="flex items-center gap-2 text-sm font-medium hover:opacity-80">
          <ArrowLeft className="h-4 w-4" /> Back to EduBel
        </Link>
        <Badge variant="outline" className="text-xs">Authenticity Check</Badge>
      </header>

      <main className="flex-1 flex items-center justify-center p-4">
        <Card className="w-full max-w-md shadow-lg">
          <CardHeader className="text-center">
            {status === 'loading' && (
              <div className="flex flex-col items-center gap-3">
                <Loader2 className="h-12 w-12 animate-spin text-primary" />
                <CardTitle>Verifying report card…</CardTitle>
              </div>
            )}
            {status === 'valid' && (
              <div className="flex flex-col items-center gap-3">
                <div className="h-20 w-20 rounded-full bg-green-500/15 flex items-center justify-center animate-scale-in">
                  <ShieldCheck className="h-12 w-12 text-green-600" />
                </div>
                <CardTitle className="text-green-700 dark:text-green-400">✓ Original Report Card</CardTitle>
                <p className="text-sm text-muted-foreground">
                  This document was generated by EduBel and has not been altered.
                </p>
              </div>
            )}
            {status === 'invalid' && (
              <div className="flex flex-col items-center gap-3">
                <div className="h-20 w-20 rounded-full bg-destructive/15 flex items-center justify-center animate-scale-in">
                  <ShieldAlert className="h-12 w-12 text-destructive" />
                </div>
                <CardTitle className="text-destructive">⚠ Tampered or Fake</CardTitle>
                <p className="text-sm text-muted-foreground">
                  Signature does not match. The data may have been edited or the QR was copied from a different report.
                </p>
              </div>
            )}
            {status === 'no-data' && (
              <div className="flex flex-col items-center gap-3">
                <div className="h-20 w-20 rounded-full bg-muted flex items-center justify-center">
                  <Camera className="h-12 w-12 text-muted-foreground" />
                </div>
                <CardTitle>No Report Data</CardTitle>
                <p className="text-sm text-muted-foreground">
                  Open this page by scanning the QR on a report card. Direct visits won't show results.
                </p>
              </div>
            )}
          </CardHeader>

          {payload && status !== 'no-data' && (
            <CardContent>
              <div className="rounded-lg border border-border/60 divide-y divide-border/60 text-sm">
                <Row label="Student" value={payload.s} />
                <Row label="School" value={payload.sc} />
                <Row label="Class" value={payload.c} />
                {payload.y && <Row label="Academic Year" value={payload.y} />}
                {payload.t && <Row label="Term" value={payload.t} />}
                <Row label="Overall %" value={`${payload.p}%`} />
                {payload.r ? <Row label="Rank" value={`#${payload.r}`} /> : null}
                <Row label="Issued" value={new Date(payload.ts).toLocaleString()} />
              </div>
              {status === 'invalid' && (
                <p className="text-xs text-destructive mt-3 text-center">
                  These values do not match the original signature — treat them as untrusted.
                </p>
              )}
            </CardContent>
          )}
        </Card>
      </main>

      <footer className="text-center text-[11px] text-muted-foreground py-3">
        EduBel · Privacy-first report cards · No personal data is sent to any server
      </footer>
    </div>
  );
};

const Row = ({ label, value }: { label: string; value: string }) => (
  <div className="flex items-center justify-between gap-4 px-3 py-2">
    <span className="text-muted-foreground">{label}</span>
    <span className="font-medium text-right break-words">{value}</span>
  </div>
);

export default Verify;
